// "2026-05-20" vira "20 de maio de 2026"
function discDate(iso) {
  var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso || ""));
  if (!m) return String(iso || "");
  var mes = DISC_MONTHS[parseInt(m[2], 10) - 1] || m[2];
  return parseInt(m[3], 10) + " de " + mes + " de " + m[1];
}

// Junta uma lista de nomes sem "&" e sem dois-pontos
function discJoin(arr) {
  var list = (arr || []).filter(function(v) { return !!v; });
  if (!list.length) return "";
  if (list.length === 1) return list[0];
  return list.slice(0, -1).join(", ") + " e " + list[list.length - 1];
}

function discCapital(s) {
  s = String(s || "");
  return s ? s.charAt(0).toUpperCase() + s.slice(1) : s;
}

// Soma a duração das faixas e devolve no formato m:ss
function discDuration(tracks) {
  var total = 0;
  (tracks || []).forEach(function(t) {
    var parts = String(t.duration || "").split(":").map(Number);
    if (parts.length === 2 && parts[0] >= 0 && parts[1] >= 0) total += parts[0] * 60 + parts[1];
  });
  if (!total) return "";
  var m = Math.floor(total / 60);
  var s = total % 60;
  return m + ":" + (s < 10 ? "0" : "") + s;
}

// Monta a ficha técnica de um lançamento
function discSpec(item, credited, mainArtist, others, tracks) {
  var spec = [];
  spec.push({ icon: "disc", label: "tipo", value: credited ? "lançamento" : "participação" });
  spec.push({ icon: "calendar", label: "data", value: discDate(item.releaseDate) });
  spec.push({ icon: "user", label: "artista", value: mainArtist });
  if (others.length) spec.push({ icon: "group", label: "participantes", value: discJoin(others) });
  spec.push({ icon: "tag", label: "selo", value: item.label || "não informado" });
  spec.push({ icon: "sliders", label: "funções", value: discJoin(item.roles) || "não informado" });
  spec.push({ icon: "wave", label: "gêneros", value: discJoin(item.genres) || "não informado" });
  spec.push({ icon: "music", label: "faixas", value: String(tracks.length) });
  var dur = discDuration(tracks);
  if (dur) spec.push({ icon: "clock", label: "duração", value: dur });
  return spec;
}

// Texto da descrição, montado só com o que o SSOT traz
function discDescription(item, credited, mainArtist, others, tracks) {
  var roles = discCapital(discJoin(item.roles));
  var n = tracks.length;
  var contagem = n === 1 ? "1 faixa" : n + " faixas";
  var partes = [];

  if (credited) {
    if (mainArtist.toLowerCase() === "matesu") {
      partes.push("Lançamento solo de Matesu.");
      if (roles) partes.push(roles + ".");
    } else {
      partes.push("Lançamento de " + mainArtist + (others.length ? " com " + discJoin(others) : "") + ".");
      if (roles) partes.push("Matesu responde por " + roles.toLowerCase() + ".");
    }
  } else {
    partes.push("Participação de Matesu em " + item.title + ", de " + mainArtist + (others.length ? " com " + discJoin(others) : "") + ".");
    if (roles) partes.push("Matesu responde por " + roles.toLowerCase() + ".");
  }

  partes.push(contagem + ".");
  return partes.join(" ");
}

// Links externos do lançamento
function discLinks(item) {
  var out = [];
  var links = item.externalLinks || {};
  Object.keys(links).forEach(function(k) {
    var url = links[k];
    if (!url) return;
    var label = DISC_LINKS[k.toLowerCase()] || discCapital(k);
    out.push({ label: label, url: url });
  });
  return out;
}

// A discografia viaja com o site (assets/js/data-discography.js), não por
// fetch: assim o portfólio abre igual em http e em file://. Os .json
// continuam sendo a fonte; tools/embed-data.mjs regenera o arquivo.
function discApplyCatalog() {
  var data = window.MATESU_DISCOGRAPHY || {};
  var items = data.items || [];
  var covers = data.covers || {};

  var grupos = {};
  grupos["lançamentos"] = {};
  grupos["participações"] = {};

  items.forEach(function(item) {
    var credited = !!item.matesuCredited;
    var grupo = credited ? "lançamentos" : "participações";
    var y = String(item.year || String(item.releaseDate || "").slice(0, 4) || "");
    if (!y) return;
    if (!grupos[grupo][y]) grupos[grupo][y] = {};

    var mainArtist = item.artist || "";
    var others = (item.artists || []).filter(function(a) { return a !== mainArtist; });
    var tracks = item.tracks || [];
    var cover = covers[item.title] || {};

    var key = item.title;
    if (grupos[grupo][y][key]) key = item.title + " · " + mainArtist;

    var rel = {
      title: item.title,
      meta: mainArtist + " · " + discDate(item.releaseDate),
      body: discDescription(item, credited, mainArtist, others, tracks),
      date: item.releaseDate,
      spec: discSpec(item, credited, mainArtist, others, tracks),
      tracks: tracks,
      links: discLinks(item)
    };
    if (cover.local) rel.img = cover.local;

    grupos[grupo][y][key] = rel;
  });

  ["lançamentos", "participações"].forEach(function(g) {
    var ordered = {};
    Object.keys(grupos[g]).sort(function(a, b) {
      return parseInt(b, 10) - parseInt(a, 10);
    }).forEach(function(y) {
      ordered[y] = grupos[g][y];
    });
    grupos[g] = ordered;
  });

  tree["música"]["lançamentos"] = grupos["lançamentos"];
  tree["música"]["participações"] = grupos["participações"];
  return items.length;
}

discApplyCatalog();

function resolve(targetPath) {
  var cur = tree;
  for (var i = 0; i < targetPath.length; i++) {
    if (!cur || typeof cur !== "object") return null;
    cur = cur[targetPath[i]];
  }
  return cur;
}

